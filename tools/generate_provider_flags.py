#!/usr/bin/env python3
"""Render the provider library's country flags from a pinned flag-icons release.

  generate_provider_flags.py generate --source flag-icons-7.6.0.tgz
  generate_provider_flags.py check

`generate` verifies the release archive, renders each two-letter 4:3 flag with
Inkscape to a lossless WebP, and writes the drawables, the code-to-drawable map
and a manifest of every output's hash. `check` needs no Inkscape: it confirms
that the drawables, the map and the license text match the manifest exactly,
so a hand edit or a stray file fails. The apps clip and outline the images, so
the art itself stays square-cornered and flat (docs/CONSUMER_SERVICES.md).
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tempfile

LIBRARY = Path(__file__).resolve().parent.parent / "provider-library"
DRAWABLES = LIBRARY / "src/main/res/drawable-nodpi"
MAP = LIBRARY / "src/main/java/com/fixcraft/yume/consumer/ProviderFlags.kt"
FLAGS = LIBRARY / "src/flags"
MANIFEST = FLAGS / "manifest.json"
LICENSE = FLAGS / "LICENSE-flag-icons"

SOURCE = {
    "name": "flag-icons",
    "version": "7.6.0",
    "url": "https://registry.npmjs.org/flag-icons/-/flag-icons-7.6.0.tgz",
    "sha256": "99d6feb80562dcaa83700ef184094d7c7b6587cc216b3fab1546cb1643e611a9",
    "license": "MIT",
}
WIDTH, HEIGHT = 128, 96
CODE = re.compile(r"package/flags/4x3/([a-z]{2})\.svg")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def kotlin_map(codes: list[str]) -> str:
    entries = "\n".join(f'        "{code.upper()}" to R.drawable.flag_{code},' for code in codes)
    return f"""// Generated by tools/generate_provider_flags.py from {SOURCE['name']} {SOURCE['version']}
// ({SOURCE['license']}, src/flags/). Do not edit.
package com.fixcraft.yume.consumer

import com.fixcraft.yume.providerlibrary.R

/**
 * Flat 4:3 flags for operator-declared ISO 3166-1 region codes, the same art in
 * every app. The caller clips and outlines them and shows its globe for a code
 * with no flag here.
 */
object ProviderFlags {{
    /** The drawable for an upper-case two-letter [country], or null. */
    fun drawable(country: String): Int? = FLAGS[country]

    private val FLAGS: Map<String, Int> = mapOf(
{entries}
    )
}}
"""


def render(svg: bytes, inkscape: str, work: Path) -> bytes:
    from PIL import Image  # Only generation needs Pillow and Inkscape.
    source = work / "flag.svg"
    target = work / "flag.png"
    source.write_bytes(svg)
    subprocess.run([inkscape, "--export-type=png", f"--export-width={WIDTH}", f"--export-height={HEIGHT}",
                    f"--export-filename={target}", str(source)], check=True, capture_output=True, timeout=120)
    with Image.open(target) as image:
        if image.size != (WIDTH, HEIGHT):
            raise ValueError("Inkscape rendered the wrong size")
        output = io.BytesIO()
        image.convert("RGBA").save(output, "WEBP", lossless=True, quality=100, method=6, exact=True)
    return output.getvalue()


def generate(archive: Path, inkscape: str) -> None:
    data = archive.read_bytes()
    if sha256(data) != SOURCE["sha256"]:
        raise ValueError("flag-icons archive differs from the pinned release")
    svgs: dict[str, bytes] = {}
    license_text = None
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            if not member.isfile() or member.size > 1 << 20:
                continue
            match = CODE.fullmatch(member.name)
            if match:
                svgs[match.group(1)] = tar.extractfile(member).read()
            elif member.name == "package/LICENSE":
                license_text = tar.extractfile(member).read()
    if license_text is None or not svgs:
        raise ValueError("flag-icons archive lacks its license or flags")
    version = subprocess.run([inkscape, "--version"], check=True, capture_output=True, text=True,
                             timeout=60).stdout.strip()
    DRAWABLES.mkdir(parents=True, exist_ok=True)
    FLAGS.mkdir(parents=True, exist_ok=True)
    for old in DRAWABLES.glob("flag_*.webp"):
        old.unlink()
    files = {}
    with tempfile.TemporaryDirectory() as work:
        for code in sorted(svgs):
            webp = render(svgs[code], inkscape, Path(work))
            (DRAWABLES / f"flag_{code}.webp").write_bytes(webp)
            files[code] = sha256(webp)
    codes = sorted(files)
    MAP.write_text(kotlin_map(codes))
    LICENSE.write_bytes(license_text)
    manifest = {"schema": 1, "source": SOURCE, "renderer": version, "size": [WIDTH, HEIGHT],
                "license_sha256": sha256(license_text), "map_sha256": sha256(MAP.read_bytes()), "files": files}
    MANIFEST.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    print(f"rendered {len(codes)} flags with {version}")


def check() -> list[str]:
    manifest = json.loads(MANIFEST.read_text())
    problems = []
    if manifest.get("schema") != 1 or manifest.get("source") != SOURCE:
        problems.append("manifest names another source")
    files = manifest.get("files", {})
    present = {path.name for path in DRAWABLES.glob("flag_*")}
    expected = {f"flag_{code}.webp" for code in files}
    problems += [f"unlisted drawable {name}" for name in sorted(present - expected)]
    for code, digest in sorted(files.items()):
        path = DRAWABLES / f"flag_{code}.webp"
        if not re.fullmatch(r"[a-z]{2}", code):
            problems.append(f"invalid code {code}")
        elif not path.is_file() or path.is_symlink():
            problems.append(f"missing drawable flag_{code}.webp")
        elif sha256(path.read_bytes()) != digest:
            problems.append(f"changed drawable flag_{code}.webp")
    if MAP.read_text() != kotlin_map(sorted(files)) or sha256(MAP.read_bytes()) != manifest.get("map_sha256"):
        problems.append("ProviderFlags.kt differs from the manifest")
    if not LICENSE.is_file() or sha256(LICENSE.read_bytes()) != manifest.get("license_sha256"):
        problems.append("flag-icons license text differs")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    make = commands.add_parser("generate")
    make.add_argument("--source", type=Path, required=True, help="the pinned flag-icons release archive")
    make.add_argument("--inkscape", default="inkscape")
    commands.add_parser("check")
    arguments = parser.parse_args()
    if arguments.command == "generate":
        generate(arguments.source, arguments.inkscape)
    problems = check()
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
